"""Build the synchronous browser catalog from the server's JSON source."""
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
items = json.loads((root / 'assets/shop-catalog.json').read_text(encoding='utf-8'))
assert len({item['id'] for item in items}) == len(items)
for slot in ['head', 'shoes', 'shirt', 'pants', 'object']:
    assert sum(item['slot'] == slot for item in items) == 20
output = '// Generated by scripts/build-shop-catalog.py; edit assets/shop-catalog.json.\n'
output += 'export const SHOP_ITEMS = ' + json.dumps(items, ensure_ascii=False, separators=(',', ':')) + ';\n'
(root / 'assets/js/shop-catalog.js').write_text(output, encoding='utf-8')
