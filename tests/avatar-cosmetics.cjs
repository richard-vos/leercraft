const assert=require('node:assert/strict');
const {pathToFileURL}=require('node:url');
const path=require('node:path');
(async()=>{
  const load=file=>import(pathToFileURL(path.resolve(file)).href);
  const THREE=await load('assets/vendor/three-0.160.0.module.js');
  const {createRunnerCharacter}=await load('assets/js/minecraft-runner-visuals.js');
  const {applyRunnerOutfit,applySeaOutfit}=await load('assets/js/avatar-cosmetics.js');
  const steve=createRunnerCharacter('steve',1.4);
  const original=steve.userData.shirtVertices.map(layer=>Array.from(layer.colors.array));
  assert(original.length>0,'Runner shirt vertices must be identifiable');
  applyRunnerOutfit(THREE,steve,{head:'gouden-kroon',shirt:'roze-shirt'});
  assert(steve.getObjectByName('avatar-crown'));
  assert(new THREE.Box3().setFromObject(steve).max.y+1<5.1,'Crown must fit below the RekenCraft gate board');
  assert(steve.userData.shirtVertices.some((layer,i)=>JSON.stringify(Array.from(layer.colors.array))!==JSON.stringify(original[i])));
  applyRunnerOutfit(THREE,steve,{head:'gouden-kroon',shirt:'roze-shirt'});
  assert.equal(steve.children.filter(c=>c.name==='avatar-crown').length,1,'Equipment must not accumulate');
  applyRunnerOutfit(THREE,steve,{});
  assert(!steve.getObjectByName('avatar-crown'));
  steve.userData.shirtVertices.forEach((layer,i)=>assert.deepEqual(Array.from(layer.colors.array),original[i],'Logout restores the original shirt'));
  const originalMaterial=new THREE.MeshStandardMaterial({color:0x18aeb7});
  const seaHero=new THREE.Group(),shirt=new THREE.Mesh(new THREE.BoxGeometry(1,1,1),originalMaterial);
  seaHero.add(shirt);const npc=new THREE.Mesh(new THREE.BoxGeometry(1,1,1),originalMaterial);
  applySeaOutfit(THREE,seaHero,{head:'gouden-kroon',shirt:'roze-shirt'});
  assert.equal(shirt.material.color.getHex(),0xe46ba0);
  assert.equal(npc.material.color.getHex(),0x18aeb7,'Shared NPC material must not be modified');
  assert(seaHero.getObjectByName('avatar-crown'));
  applySeaOutfit(THREE,seaHero,{});
  assert.equal(shirt.material,originalMaterial);assert(!seaHero.getObjectByName('avatar-crown'));
  console.log('Passed: crown and pink shirt in both renderers, repeat equip, default Steve restoration and NPC isolation.');
})().catch(error=>{console.error(error);process.exitCode=1;});
